/** Текст соглашения одной строкой — для файла AGREEMENT.md и копирования. */
export function agreementAsMarkdown(): string {
  const lines = [
    '# Лицензионное соглашение Git it',
    '',
    `Версия ${AGREEMENT_VERSION} от ${AGREEMENT_UPDATED_AT}`,
    '',
    'Используя веб-приложение «Git it», вы подтверждаете, что прочитали и принимаете условия ниже.',
    '',
  ]
  for (const section of AGREEMENT_SECTIONS) {
    lines.push(`## ${section.title}`, '')
    for (const paragraph of section.paragraphs) lines.push(paragraph, '')
  }
  return lines.join('\n')
}

/** Насколько близко к низу считается «дочитано» (px). */
export const AGREEMENT_BOTTOM_TOLERANCE = 24

/**
 * Считает, дочитал ли пользователь текст. Чистая функция — её поведение
 * проверяется тестами, включая случай, когда текст целиком помещается на экран.
 */
export function evaluateAgreementScroll(input: {
  scrollTop: number
  scrollHeight: number
  clientHeight: number
}): { atEnd: boolean; percent: number } {
  // пока браузер не посчитал размеры блока, считать текст прочитанным нельзя
  if (input.clientHeight <= 0 || input.scrollHeight <= 0) return { atEnd: false, percent: 0 }

  const scrollable = Math.max(0, input.scrollHeight - input.clientHeight)
  const atEnd =
    scrollable <= AGREEMENT_BOTTOM_TOLERANCE ||
    input.scrollTop + input.clientHeight >= input.scrollHeight - AGREEMENT_BOTTOM_TOLERANCE
  const percent = scrollable <= 0 ? 100 : Math.min(100, Math.max(0, Math.round((input.scrollTop / scrollable) * 100)))
  return { atEnd, percent }
}

export interface AgreementAcceptance {
  version: string
  acceptedAt: string
}

export function readAcceptance(): AgreementAcceptance | null {
  const saved = storage.getJSON<AgreementAcceptance | null>(STORAGE_KEYS.agreement, null)
  if (!saved || typeof saved.version !== 'string' || typeof saved.acceptedAt !== 'string') return null
  return saved
}

/** Принята ли действующая версия соглашения. */
export function isAgreementAccepted(): boolean {
  const saved = readAcceptance()
  return saved?.version === AGREEMENT_VERSION
}

export function saveAcceptance(): AgreementAcceptance {
  const acceptance: AgreementAcceptance = { version: AGREEMENT_VERSION, acceptedAt: new Date().toISOString() }
  storage.setJSON(STORAGE_KEYS.agreement, acceptance)
  return acceptance
}

export function clearAcceptance(): void {
  storage.remove(STORAGE_KEYS.agreement)
}

/** «версии 1.0 от 16 сентября 2026» — для подписи ссылки в подвале. */
export function formatAgreementVersion(): string {
  return `(версия ${AGREEMENT_VERSION} от ${AGREEMENT_UPDATED_AT})`
}

export function formatAcceptanceDate(iso: string): string {
  const date = new Date(iso)
  if (Number.isNaN(date.getTime())) return '—'
  return date.toLocaleString('ru-RU', { day: 'numeric', month: 'long', year: 'numeric', hour: '2-digit', minute: '2-digit' })
}
